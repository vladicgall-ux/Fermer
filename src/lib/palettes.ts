// Цвета меток рабочих: назначаются автоматически и одинаковы на всех устройствах, в настройках не меняются.
// 20 контрастных цветов, заметных и на спутниковом снимке, и на схеме; порядок подобран так,
// чтобы у соседних по порядку рабочих цвета заметно различались.
export const WORKER_COLORS = [
  '#e53935', // красный
  '#1e88e5', // синий
  '#fdd835', // жёлтый
  '#8e24aa', // фиолетовый
  '#00e5ff', // бирюзовый
  '#fb8c00', // оранжевый
  '#76ff03', // салатовый
  '#d81b60', // малиновый
  '#212121', // чёрный
  '#1de9b6', // мятный
  '#6d4c41', // коричневый
  '#ff80ab', // розовый
  '#3949ab', // индиго
  '#c0ca33', // оливковый
  '#ffffff', // белый
  '#00897b', // морская волна
  '#ff6e40', // коралловый
  '#651fff', // ультрамарин
  '#9e9e9e', // серый
  '#ffc400', // янтарный
]

/**
 * Цвет рабочего по порядку появления в приложении (id по возрастанию): у уже существующих рабочих
 * цвет не меняется при добавлении новых.
 */
export function makeColorFor(workerIds: number[]): (id: number) => string {
  const rank = new Map([...workerIds].sort((a, b) => a - b).map((id, i) => [id, i]))
  return (id) => WORKER_COLORS[(rank.get(id) ?? id) % WORKER_COLORS.length]
}

/** Цвет текста поверх цвета метки: тёмный на светлых, белый на тёмных. */
export function textOn(hex: string): string {
  const n = parseInt(hex.slice(1), 16)
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255]
  return 0.299 * r + 0.587 * g + 0.114 * b > 150 ? '#1c1c1e' : '#ffffff'
}

/** Обводка метки: белая, а у очень светлых цветов (белый, жёлтый) — тёмная, чтобы метка не сливалась. */
export function borderFor(hex: string): string {
  const n = parseInt(hex.slice(1), 16)
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255]
  return 0.299 * r + 0.587 * g + 0.114 * b > 200 ? '#37474f' : '#ffffff'
}
